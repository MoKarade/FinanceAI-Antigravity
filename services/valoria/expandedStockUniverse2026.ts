import type {
  RawExpandedEntry,
  VerifiedTrailingReturnSnapshot,
} from './verifiedMarketHistory2026';

interface ExpandedStockSeed {
  entry: RawExpandedEntry;
  trailing: VerifiedTrailingReturnSnapshot;
}

function makeStockSeed(params: {
  id: string;
  ticker: string;
  name: string;
  subClass: 'action_ca' | 'action_us' | 'action_eu_asia';
  sector: string;
  region: 'Canada (TSX)' | 'États-Unis (NYSE/NASDAQ)' | 'Europe & Asie';
  spotCad: number;
  divPct: number;
  expRetPct: number;
  volPct: number;
  beta: number;
  peForward: number;
  evEbitda: number;
  fcfYieldPct: number;
  roicPct: number;
  roePct: number;
  opMarginPct: number;
  epsGrowthPct: number;
  netDebtEbitda: number;
  piotroski: number;
  altmanZ: number;
  fairUpsidePct: number;
  description: string;
  catalyst: string;
  r1dPct: number;
  r5dPct: number;
  r1mPct: number;
  r3mPct: number;
  r6mPct: number;
  r12mPct: number;
  high52wRatio: number;
  low52wRatio: number;
}): ExpandedStockSeed {
  const categoryLabel =
    params.subClass === 'action_ca'
      ? 'Actions Canada (TSX)'
      : params.subClass === 'action_us'
        ? 'Actions États-Unis'
        : 'Actions Europe & Asie';
  const wrapper =
    params.subClass === 'action_ca'
      ? 'CELI · REER · Non-enregistré'
      : params.subClass === 'action_us'
        ? 'REER · CELI'
        : 'CELI · Non-enregistré';
  const drift = Number(
    Math.max(-0.012, Math.min(0.015, params.r6mPct / 1800)).toFixed(4)
  );

  return {
    entry: {
      id: params.id,
      ticker: params.ticker,
      name: params.name,
      category: 'actions',
      categoryLabel,
      subClass: params.subClass,
      wrapper,
      sector: params.sector,
      region: params.region,
      spotCad2026: params.spotCad,
      dividendYieldPct: params.divPct,
      annualFeePct: 0,
      baseExpectedReturnPct: params.expRetPct,
      baseVolatilityPct: params.volPct,
      growthBeta: params.beta,
      inflationBeta: /Énergie|Mines|Matériaux/.test(params.sector) ? 0.35 : -0.2,
      rateSensitivity: /Services Publics|Télécoms/.test(params.sector) ? -0.55 : -0.32,
      crisisConvexity: -0.35,
      recentTrendDrift: drift,
      description: params.description,
      stockFund: {
        peForward: params.peForward,
        evEbitda: params.evEbitda,
        fcfYieldPct: params.fcfYieldPct,
        roicPct: params.roicPct,
        roePct: params.roePct,
        operatingMarginPct: params.opMarginPct,
        epsGrowthNextYrPct: params.epsGrowthPct,
        netDebtToEbitda: params.netDebtEbitda,
        piotroskiFScore: params.piotroski,
        altmanZScore: params.altmanZ,
        baseFairValueUpsidePct: params.fairUpsidePct,
        catalystHeadline: params.catalyst,
      },
    },
    trailing: {
      r1dPct: params.r1dPct,
      r5dPct: params.r5dPct,
      r1mPct: params.r1mPct,
      r3mPct: params.r3mPct,
      r6mPct: params.r6mPct,
      r12mPct: params.r12mPct,
      high52wCad: Number((params.spotCad * params.high52wRatio).toFixed(2)),
      low52wCad: Number((params.spotCad * params.low52wRatio).toFixed(2)),
    },
  };
}

