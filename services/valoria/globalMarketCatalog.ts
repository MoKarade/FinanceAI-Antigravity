export function getAssetSubClass(asset: FinancialAsset): MarketAssetSubClass {
  const mapped = SUBCLASS_BY_ASSET_ID[asset.id];
  if (mapped) return mapped;
  if (asset.category === 'crypto') return 'crypto_l1_defi';
  if (asset.category === 'obligations') return 'obligation_taux';
  if (asset.category === 'refuge') return 'matiere_premiere';
  if (asset.ticker.endsWith('.TO')) return 'action_ca';
  if (asset.region === 'États-Unis (CTO)') return 'action_us';
  if (asset.isIndividualStock) return 'action_eu_asia';
  return 'etf_indice';
}

export function registerDynamicCatalogProfile(params: {
  assetId: string;
  subClass: MarketAssetSubClass;
  cryptoFund?: CryptoAnalystProfile;
  macroFund?: FundOrMacroAnalystProfile;
}): void {
  SUBCLASS_BY_ASSET_ID[params.assetId] = params.subClass;
  if (params.cryptoFund) {
    CRYPTO_FUNDAMENTALS[params.assetId] = params.cryptoFund;
  }
  if (params.macroFund) {
    MACRO_FUND_PROFILES[params.assetId] = params.macroFund;
  }
}

